#include <stdlib.h>
#include <string.h>
#include <time.h>


static const char* kActionPrefix = "org.vitruvian.";
static const char* kAlwaysAskKey = "org.vos.polkit.always-ask";


static int
append_text(char* out, size_t outSize, size_t* used, const char* format, ...)
{
	if (*used >= outSize)
		return -1;

	va_list args;
	va_start(args, format);
	int written = vsnprintf(out + *used, outSize - *used, format, args);
	va_end(args);

	if (written < 0 || (size_t)written >= outSize - *used)
		return -1;

	*used += (size_t)written;
	return 0;
}


int
grant_escape_js(const char* text, char* out, size_t outSize)
{
	if (text == NULL || out == NULL || outSize == 0)
		return -1;

	size_t used = 0;
	for (const char* p = text; *p != '\0'; p++) {
		char chunk[3];
		size_t chunkLen = 1;
		if (*p == '"' || *p == '\\') {
			chunk[0] = '\\';
			chunk[1] = *p;
			chunkLen = 2;
		} else if ((unsigned char)*p < 0x20) {
			// Control characters would break the rule file; drop them.
			continue;
		} else
			chunk[0] = *p;

		if (used + chunkLen + 1 > outSize)
			return -1;
		memcpy(out + used, chunk, chunkLen);
		used += chunkLen;
	}

	out[used] = '\0';
	return (int)used;
}


int
grant_format_state(const GrantRecord& record, char* out, size_t outSize)
{
	int written = snprintf(out, outSize,
		"user=%s\nsession=%s\nminutes=%d\nexpires=%lld\n",
		record.user, record.session, record.minutes,
		(long long)record.expiresUnix);
	if (written < 0 || (size_t)written >= outSize)
		return -1;
	return written;
}


bool
grant_parse_state(const char* text, GrantRecord& record)
{
	if (text == NULL)
		return false;

	memset(&record, 0, sizeof(record));

	const char* p = text;
	while (*p != '\0') {
		const char* lineEnd = strchr(p, '\n');
		size_t length = lineEnd != NULL
			? (size_t)(lineEnd - p) : strlen(p);
		char line[256];
		if (length >= sizeof(line))
			return false;
		memcpy(line, p, length);
		line[length] = '\0';

		char* value = strchr(line, '=');
		if (value != NULL) {
			*value++ = '\0';
			if (strcmp(line, "user") == 0) {
				if (strlen(value) >= sizeof(record.user))
					return false;
				strcpy(record.user, value);
			} else if (strcmp(line, "session") == 0) {
				if (strlen(value) >= sizeof(record.session))
					return false;
				strcpy(record.session, value);
			} else if (strcmp(line, "minutes") == 0)
				record.minutes = atoi(value);
			else if (strcmp(line, "expires") == 0)
				record.expiresUnix = atoll(value);
		}

		if (lineEnd == NULL)
			break;
		p = lineEnd + 1;
	}

	if (record.user[0] == '\0' || record.session[0] == '\0'
		|| record.minutes <= 0 || record.expiresUnix <= 0)
		return false;
	return true;
}


int
grant_render_rules(const GrantRecord* records, int recordCount,
	const char* const* alwaysAsk, int alwaysAskCount, char* out,
	size_t outSize, int64_t nowUnix)
{
	if (out == NULL || outSize == 0 || records == NULL)
		return -1;
	if (recordCount < 0 || recordCount > kGrantMaxRecords
		|| alwaysAskCount < 0 || alwaysAskCount > kGrantMaxAlwaysAsk)
		return -1;

	size_t used = 0;

	if (append_text(out, outSize, &used,
			"// Generated by vos-polkit-grant-helper; do not edit.\n"
			"// One entry per remembered-admin grant; the deadline is\n"
			"// enforced here so expiry does not depend on the helper\n"
			"// being alive to unlink this file.\n") != 0)
		return -1;

	if (append_text(out, outSize, &used,
			"polkit.addRule(function(action, subject) {\n") != 0)
		return -1;

	// Escaped action prefix: constant, but keep one code path for
	// embedding strings.
	char prefix[32];
	if (grant_escape_js(kActionPrefix, prefix, sizeof(prefix)) < 0)
		return -1;
	if (append_text(out, outSize, &used,
			"\tif (action.id.indexOf(\"%s\") != 0)\n"
			"\t\treturn polkit.Result.NOT_HANDLED;\n", prefix) != 0)
		return -1;

	if (append_text(out, outSize, &used, "\tvar alwaysAsk = [") != 0)
		return -1;
	for (int i = 0; i < alwaysAskCount; i++) {
		char escaped[256];
		if (alwaysAsk[i] == NULL
			|| grant_escape_js(alwaysAsk[i], escaped, sizeof(escaped)) < 0)
			return -1;
		if (append_text(out, outSize, &used, "%s\"%s\"",
				i > 0 ? ", " : "", escaped) != 0)
			return -1;
	}
	if (append_text(out, outSize, &used, "];\n") != 0)
		return -1;

	if (append_text(out, outSize, &used,
			"\tif (alwaysAsk.indexOf(action.id) >= 0)\n"
			"\t\treturn polkit.Result.NOT_HANDLED;\n"
			"\tif (subject.session == null)\n"
			"\t\treturn polkit.Result.NOT_HANDLED;\n"
			"\tvar grants = [\n") != 0)
		return -1;

	for (int i = 0; i < recordCount; i++) {
		if (records[i].expiresUnix <= nowUnix)
			continue;

		char user[128];
		char session[256];
		if (grant_escape_js(records[i].user, user, sizeof(user)) < 0
			|| grant_escape_js(records[i].session, session,
				sizeof(session)) < 0)
			return -1;

		if (append_text(out, outSize, &used,
				"\t\t{ user: \"%s\", session: \"%s\", "
				"expires: %lld },\n", user, session,
				(long long)records[i].expiresUnix * 1000) != 0)
			return -1;
	}

	if (append_text(out, outSize, &used,
			"\t];\n"
			"\tvar now = Date.now();\n"
			"\tfor (var i = 0; i < grants.length; i++) {\n"
			"\t\tif (grants[i].user == subject.user\n"
			"\t\t\t&& grants[i].session == subject.session\n"
			"\t\t\t&& now < grants[i].expires)\n"
			"\t\t\treturn polkit.Result.YES;\n"
			"\t}\n"
			"\treturn polkit.Result.NOT_HANDLED;\n"
			"});\n") != 0)
		return -1;

	return (int)used;
}


int
grant_scan_always_ask(const char* policyText, const char** ids, int maxIds)
{
	if (policyText == NULL || ids == NULL || maxIds <= 0)
		return 0;

	static const char* kActionTag = "<action id=\"";
	static const char* kActionEnd = "</action>";
	const size_t tagLength = strlen(kActionTag);
	const size_t endLength = strlen(kActionEnd);

	int found = 0;
	const char* p = policyText;
	while (found < maxIds && (p = strstr(p, kActionTag)) != NULL) {
		p += tagLength;
		const char* idStart = p;
		const char* idEnd = strchr(idStart, '"');
		if (idEnd == NULL)
			break;
		const char* blockEnd = strstr(idEnd, kActionEnd);
		if (blockEnd == NULL)
			break;

		const char* key = strstr(idEnd, kAlwaysAskKey);
		if (key != NULL && key < blockEnd) {
			const char* value = strstr(key, ">true<");
			if (value != NULL && value < blockEnd) {
				size_t idLength = (size_t)(idEnd - idStart);
				if (idLength > 0 && idLength < 256) {
					char* id = (char*)malloc(idLength + 1);
					if (id != NULL) {
						memcpy(id, idStart, idLength);
						id[idLength] = '\0';
						ids[found++] = id;
					}
				}
			}
		}

		p = blockEnd + endLength;
	}
	return found;
}


bool
grant_session_is_sane(const char* session)
{
	if (session == NULL || *session == '\0')
		return false;

	size_t length = strlen(session);
	if (length >= 128)
		return false;

	for (size_t i = 0; i < length; i++) {
		char c = session[i];
		bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
			|| (c >= '0' && c <= '9') || c == '-' || c == '_';
		if (!ok)
			return false;
	}
	return true;
}
